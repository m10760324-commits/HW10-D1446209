def ad_report(impressions, clicks, target=3.0):
    """計算廣告 CTR 與是否達標，回傳 (ctr, passed)。"""
    if impressions == 0:
        return (None, False)

    if clicks == 0:
        ctr = 0.0
    else:
        ctr = clicks / impressions * 100

    passed = ctr >= target
    return (ctr, passed)


def format_report_lines(student_id, target, ads_results, passed_count):
    """整理報表輸出文字。"""
    lines = [
        f"學號：{student_id}",
        f"CTR門檻：{target:.2f}%",
    ]
    for name, impressions, clicks, ctr, passed in ads_results:
        if ctr is None:
            ctr_text = "無曝光資料"
        else:
            ctr_text = f"{ctr:.2f}%"
        lines.append(
            f"{name}：曝光={impressions}，點擊={clicks}，CTR={ctr_text}，達標={passed}"
        )
    lines.append(f"達標廣告數：{passed_count}")
    return lines


def main():
    student_id = input("請輸入完整學號：").strip().upper()
    tail = student_id[-3:]
    a = int(student_id[-3])
    b = int(student_id[-2])
    c = int(student_id[-1])
    s = a + b + c

    ads = [
        ("搜尋廣告", 1000 + 100 * a, 30 + 5 * b),
        ("社群廣告", 1200 + 100 * b, 24 + 4 * c),
        ("影音廣告", 0, 0),
    ]
    target = 2.5 + 0.1 * c

    ads_results = []
    passed_count = 0

    for name, impressions, clicks in ads:
        ctr, passed = ad_report(impressions, clicks, target=target)
        if passed:
            passed_count += 1
        ads_results.append((name, impressions, clicks, ctr, passed))

    for line in format_report_lines(student_id, target, ads_results, passed_count):
        print(line)

    default_test = ad_report(1000, 30)
    zero_click_test = ad_report(1000, 0)
    print(f"預設門檻測試：{default_test}")
    print(f"零點擊測試：{zero_click_test}")


if __name__ == "__main__":
    main()