def collect_codes(raw_codes, saved=None):
    """整理優惠碼清單：先保留 saved，再依首次出現順序加入清洗後的新碼。"""
    result = list(saved) if saved is not None else []
    seen = set(result)

    for raw in raw_codes:
        cleaned = raw.strip().upper()
        if not cleaned:
            continue
        if cleaned not in seen:
            seen.add(cleaned)
            result.append(cleaned)

    return result


def format_output(student_id, activity_a, activity_b, saved, raw_a, empty_result):
    """整理畫面輸出文字。"""
    return [
        f"學號：{student_id}",
        f"活動A：{activity_a}",
        f"活動B：{activity_b}",
        f"原始saved：{saved}",
        f"原始raw_a：{raw_a}",
        f"空資料：{empty_result}",
    ]


def main():
    student_id = input("請輸入完整學號：").strip().upper()
    tail = student_id[-3:]
    a = int(student_id[-3])
    b = int(student_id[-2])
    c = int(student_id[-1])
    s = a + b + c

    saved = ["BASE"]
    raw_a = [" welcome" + tail + " ", "vip" + tail, "", "WELCOME" + tail, "   "]
    raw_b = [" new" + tail + " ", " welcome" + tail + " "]

    activity_a = collect_codes(raw_a, saved=saved)
    activity_b = collect_codes(raw_b)
    empty_result = collect_codes([])

    for line in format_output(student_id, activity_a, activity_b, saved, raw_a, empty_result):
        print(line)


if __name__ == "__main__":
    main()