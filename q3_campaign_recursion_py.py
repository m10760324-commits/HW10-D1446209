def cumulative_spend(daily_spend, n):
    """使用遞迴計算前 n 天的累計花費（整數元）。"""
    if n == 0 or not daily_spend:
        return 0
    return cumulative_spend(daily_spend, n - 1) + daily_spend[n - 1]


def format_output(student_id, daily_spend, n, target_total, series_totals, empty_total):
    """整理畫面輸出文字。"""
    lines = [
        f"學號：{student_id}",
        f"每日費用：{daily_spend}",
        f"指定n：{n}",
        f"指定前{n}天累計：{target_total}元",
    ]
    for day, total in series_totals:
        lines.append(f"前{day}天：{total}元")
    lines.append(f"空資料：{empty_total}元")
    return lines


def main():
    student_id = input("請輸入完整學號：").strip().upper()
    tail = student_id[-3:]
    a = int(student_id[-3])
    b = int(student_id[-2])
    c = int(student_id[-1])
    s = a + b + c

    daily_spend = [
        100 + 10 * a,
        150 + 10 * b,
        0,
        200 + 10 * c,
        50 + 10 * s,
    ]
    n = 3 + c % 3

    target_total = cumulative_spend(daily_spend, n)
    series_totals = []
    for day in range(0, 6):
        series_totals.append((day, cumulative_spend(daily_spend, day)))
    empty_total = cumulative_spend([], 0)

    for line in format_output(
        student_id, daily_spend, n, target_total, series_totals, empty_total
    ):
        print(line)


if __name__ == "__main__":
    main()