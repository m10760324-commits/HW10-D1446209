def select_clicks(raw_clicks, min_clicks=10):
    """清理點擊紀錄並篩選出達門檻的點擊數，回傳 (numbers, qualified)。"""
    stripped = map(lambda s: s.strip(), raw_clicks)
    non_empty = filter(None, stripped)
    numbers = list(map(int, non_empty))
    qualified = list(filter(lambda x: x >= min_clicks, numbers))
    return (numbers, qualified)


def format_output(
    student_id,
    min_clicks,
    numbers,
    qualified,
    ranked_qualified,
    high_threshold_qualified,
):
    """整理畫面輸出文字。"""
    lines = [
        f"學號：{student_id}",
        f"點擊門檻：{min_clicks}",
        f"清理結果：{numbers}",
        f"合格結果：{qualified}",
        f"合格筆數：{len(qualified)}",
        f"合格合計：{sum(qualified)}",
    ]
    for rank, clicks in ranked_qualified:
        lines.append(f"第{rank}名：{clicks}次")

    lines.append(f"門檻100合格結果：{high_threshold_qualified}")
    lines.append(f"門檻100合格筆數：{len(high_threshold_qualified)}")
    lines.append(f"門檻100合格合計：{sum(high_threshold_qualified)}")
    if not high_threshold_qualified:
        lines.append("無符合門檻的素材")

    return lines


def main():
    student_id = input("請輸入完整學號：").strip().upper()
    tail = student_id[-3:]
    a = int(student_id[-3])
    b = int(student_id[-2])
    c = int(student_id[-1])
    s = a + b + c

    raw_clicks = [
        str(10 + a),
        "0",
        "",
        " " + str(5 + b) + " ",
        "   ",
        str(15 + c),
        str(5 + b),
    ]
    min_clicks = 5 + b

    numbers, qualified = select_clicks(raw_clicks, min_clicks=min_clicks)
    ranked_qualified = list(enumerate(sorted(qualified, reverse=True), start=1))
    _, high_threshold_qualified = select_clicks(raw_clicks, min_clicks=100)

    for line in format_output(
        student_id,
        min_clicks,
        numbers,
        qualified,
        ranked_qualified,
        high_threshold_qualified,
    ):
        print(line)


if __name__ == "__main__":
    main()